import { jsPDF } from 'jspdf';
import { useCRMStore } from '../store/crmStore';

interface Column {
  key: string;
  label: string;
}

/**
 * Clean up text to prevent encoding/rendering bugs in jsPDF
 */
const safeText = (val: any): string => {
  if (val === null || val === undefined) return '';
  return String(val).replace(/[^\x20-\x7E]/g, ''); // limit to ASCII printable characters for standard fonts
};

/**
 * Format currency
 */
const formatCurrency = (val: any, currency: string = 'USD'): string => {
  const num = parseFloat(val);
  if (isNaN(num)) return '$0';
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: currency,
    maximumFractionDigits: 0
  }).format(num);
};

/**
 * Generate a beautiful PDF Report
 */
export async function generatePDFReport(moduleName: string, columns: Column[], data: any[]) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const settings = useCRMStore.getState().settings || {
    companyName: 'Acme Enterprise SaaS',
    companyEmail: 'finance@acme.com',
    companyPhone: '+1 (555) 019-9000',
    currency: 'USD'
  };

  const user = useCRMStore.getState().user;

  // Colors Palette
  const primaryColor = [16, 185, 129]; // Emerald Green #10b981
  const darkSlateColor = [15, 23, 42]; // Slate 900
  const lightGrayColor = [248, 250, 252]; // Slate 50
  const borderGrayColor = [226, 232, 240]; // Slate 200
  const mutedText = [100, 116, 139]; // Slate 500

  // Layout parameters
  const pageHeight = 297;
  const pageWidth = 210;
  const marginX = 15;
  let currentY = 15;

  const addNewPage = () => {
    doc.addPage();
    currentY = 15;
    drawFooter();
  };

  const drawFooter = () => {
    const totalPages = doc.getNumberOfPages();
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
    
    // Page count
    doc.text(
      `Page ${doc.getCurrentPageInfo().pageNumber}`,
      pageWidth - marginX,
      pageHeight - 10,
      { align: 'right' }
    );
    
    // Notice
    doc.text(
      `Confidential - Generated by ${user?.name || 'Staff'} (${user?.role || 'Sales Manager'}) on ${new Date().toLocaleDateString()}`,
      marginX,
      pageHeight - 10
    );
  };

  // 1. Draw Page 1 Footer
  drawFooter();

  // 2. Draw Header Area
  doc.setFillColor(darkSlateColor[0], darkSlateColor[1], darkSlateColor[2]);
  doc.rect(marginX, currentY, pageWidth - (marginX * 2), 22, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(255, 255, 255);
  doc.text(safeText(settings.companyName.toUpperCase()), marginX + 5, currentY + 9);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(200, 200, 200);
  doc.text(
    `Contact: ${settings.companyEmail} | Phone: ${settings.companyPhone}`,
    marginX + 5,
    currentY + 15
  );

  // Document Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(255, 255, 255);
  doc.text(
    `${moduleName.toUpperCase()} ANALYTICAL SUMMARY REPORT`,
    pageWidth - marginX - 5,
    currentY + 13,
    { align: 'right' }
  );

  currentY += 28;

  // 3. Stats & Metrics Block
  let totalRecordCount = data.length;
  let totalValuationSum = 0;
  let metricLabel = 'Aggregate Valuation';

  if (moduleName === 'deals' || moduleName === 'leads') {
    totalValuationSum = data.reduce((sum, item) => sum + (parseFloat(item.value) || 0), 0);
    metricLabel = 'Total Pipeline Value';
  } else if (moduleName === 'invoices') {
    totalValuationSum = data.reduce((sum, item) => sum + (parseFloat(item.total) || 0), 0);
    metricLabel = 'Total Billed Amount';
  } else if (moduleName === 'quotations') {
    totalValuationSum = data.reduce((sum, item) => sum + (parseFloat(item.total) || 0), 0);
    metricLabel = 'Total Quoted Amount';
  } else if (moduleName === 'products') {
    totalValuationSum = data.reduce((sum, item) => sum + (parseFloat(item.price) || 0), 0);
    metricLabel = 'Average Unit Price';
    if (totalRecordCount > 0) totalValuationSum = totalValuationSum / totalRecordCount;
  }

  // Draw stats box
  doc.setFillColor(lightGrayColor[0], lightGrayColor[1], lightGrayColor[2]);
  doc.setDrawColor(borderGrayColor[0], borderGrayColor[1], borderGrayColor[2]);
  doc.rect(marginX, currentY, pageWidth - (marginX * 2), 20, 'FD');

  // Draw dividers
  doc.line(marginX + 60, currentY, marginX + 60, currentY + 20);
  doc.line(marginX + 120, currentY, marginX + 120, currentY + 20);

  // Col 1: Total Records
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
  doc.text('Total Records Listed', marginX + 5, currentY + 6);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(darkSlateColor[0], darkSlateColor[1], darkSlateColor[2]);
  doc.text(String(totalRecordCount), marginX + 5, currentY + 14);

  // Col 2: Financial Aggregation
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
  doc.text(metricLabel, marginX + 65, currentY + 6);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.text(formatCurrency(totalValuationSum, settings.currency), marginX + 65, currentY + 14);

  // Col 3: Report Metadata
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(mutedText[0], mutedText[1], mutedText[2]);
  doc.text('Report Clearance', marginX + 125, currentY + 6);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(darkSlateColor[0], darkSlateColor[1], darkSlateColor[2]);
  doc.text('APPROVED / ACTIVE', marginX + 125, currentY + 14);

  currentY += 28;

  // 4. Data Table Header Row
  doc.setFillColor(primaryColor[0], primaryColor[1], primaryColor[2]);
  doc.rect(marginX, currentY, pageWidth - (marginX * 2), 8, 'F');

  // Columns layout computation
  const usableWidth = pageWidth - (marginX * 2);
  const colWidth = usableWidth / columns.length;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(255, 255, 255);

  columns.forEach((col, i) => {
    doc.text(
      safeText(col.label),
      marginX + (i * colWidth) + 3,
      currentY + 5.5
    );
  });

  currentY += 8;

  // 5. Data Rows
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(51, 65, 85); // Slate 700

  data.forEach((row, rowIdx) => {
    if (currentY > 265) {
      addNewPage();
      
      // Redraw table header on new page
      doc.setFillColor(primaryColor[0], primaryColor[1], primaryColor[2]);
      doc.rect(marginX, currentY, pageWidth - (marginX * 2), 8, 'F');
      
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8.5);
      doc.setTextColor(255, 255, 255);
      columns.forEach((col, i) => {
        doc.text(
          safeText(col.label),
          marginX + (i * colWidth) + 3,
          currentY + 5.5
        );
      });
      currentY += 8;
      
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(51, 65, 85);
    }

    // Zebra striping background
    if (rowIdx % 2 === 1) {
      doc.setFillColor(lightGrayColor[0], lightGrayColor[1], lightGrayColor[2]);
      doc.rect(marginX, currentY, pageWidth - (marginX * 2), 7.5, 'F');
    }

    // Row separator line
    doc.setDrawColor(borderGrayColor[0], borderGrayColor[1], borderGrayColor[2]);
    doc.line(marginX, currentY + 7.5, pageWidth - marginX, currentY + 7.5);

    // Populate cell content
    columns.forEach((col, colIdx) => {
      let rawVal = row[col.key];
      let formattedVal = '';

      if (rawVal === undefined || rawVal === null) {
        formattedVal = '-';
      } else if (col.key === 'value' || col.key === 'total' || col.key === 'price' || col.key === 'revenue') {
        formattedVal = formatCurrency(rawVal, settings.currency);
      } else if (col.key === 'isPrimary') {
        formattedVal = rawVal ? 'Primary' : 'Secondary';
      } else if (Array.isArray(rawVal)) {
        formattedVal = rawVal.join(', ');
      } else {
        formattedVal = String(rawVal);
      }

      // Max length truncation to prevent overlapping
      if (formattedVal.length > 28) {
        formattedVal = formattedVal.substring(0, 26) + '...';
      }

      // Bold text for first column (usually title/name) or numeric amounts
      if (colIdx === 0) {
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(darkSlateColor[0], darkSlateColor[1], darkSlateColor[2]);
      } else {
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(71, 85, 105); // Slate 600
      }

      doc.text(
        safeText(formattedVal),
        marginX + (colIdx * colWidth) + 3,
        currentY + 5
      );
    });

    currentY += 7.5;
  });

  // Save/Download PDF document
  doc.save(`CRM_Report_${moduleName}_${new Date().toISOString().split('T')[0]}.pdf`);
}

/**
 * Generate and download a formatted CSV report
 */
export function generateCSVReport(moduleName: string, columns: Column[], data: any[]) {
  if (!Array.isArray(data) || data.length === 0) {
    alert('No records available to export.');
    return;
  }

  const csvHeaders = columns.map(col => `"${col.label.replace(/"/g, '""')}"`).join(',');
  const csvRows = [
    csvHeaders,
    ...data.map(row => 
      columns.map(col => {
        let val = row[col.key];
        if (val === undefined || val === null) val = '';
        if (Array.isArray(val)) val = val.join(', ');
        const escaped = String(val).replace(/"/g, '""');
        return `"${escaped}"`;
      }).join(',')
    )
  ];

  const csvContent = csvRows.join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `CRM_Export_${moduleName}_${new Date().toISOString().split('T')[0]}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
