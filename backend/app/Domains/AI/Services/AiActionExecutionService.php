<?php

namespace App\Domains\AI\Services;

use App\Domains\AI\Models\AiProposedAction;
use App\Domains\Identity\Services\RbacService;
use App\Domains\LeadAcquisition\Models\Lead;
use App\Domains\Projects\Models\Task as CrmTask;
use App\Models\User;
use Illuminate\Support\Facades\Log;

class AiActionExecutionService
{
    public function __construct(
        protected RbacService $rbacService
    ) {}

    /**
     * Propose an operational action
     */
    public function proposeAction(int $tenantId, User $user, array $data): AiProposedAction
    {
        return AiProposedAction::create([
            'tenant_id' => $tenantId,
            'user_id' => $user->id,
            'session_id' => $data['session_id'] ?? null,
            'action_type' => $data['action_type'],
            'target_entity_type' => $data['target_entity_type'] ?? null,
            'target_entity_id' => $data['target_entity_id'] ?? null,
            'summary' => $data['summary'],
            'payload' => $data['payload'] ?? [],
            'requires_confirmation' => true,
            'status' => 'pending_confirmation',
        ]);
    }

    /**
     * Confirm and execute the proposed action with explicit permission checks.
     */
    public function confirmAndExecute(int $tenantId, int $actionId, User $user): AiProposedAction
    {
        $action = AiProposedAction::where('tenant_id', $tenantId)->findOrFail($actionId);

        if ($action->status === 'executed') {
            return $action;
        }

        // Enforce RBAC permission: Must have 'ai.execute_actions' or admin/owner role
        $role = str_replace(' ', '', strtolower($user->role ?? ''));
        $isAdmin = in_array($role, ['admin', 'owner', 'superadmin', 'super_admin']);
        $hasPermission = $isAdmin || $this->rbacService->hasPermission($user, 'ai.execute_actions');

        if (!$hasPermission) {
            throw new \Illuminate\Auth\Access\AuthorizationException(
                "Unauthorized: You lack the 'ai.execute_actions' permission required to execute proposed AI actions."
            );
        }

        // Execute the action safely
        $executionResult = [];
        $payload = $action->payload ?? [];

        switch ($action->action_type) {
            case 'create_task':
                $task = CrmTask::create([
                    'tenant_id' => $tenantId,
                    'created_by' => $user->id,
                    'assigned_user_id' => $user->id,
                    'title' => $payload['title'] ?? 'AI Follow-up Task',
                    'description' => $payload['description'] ?? 'Generated by AI Assistant',
                    'due_date' => $payload['due_date'] ?? now()->addDay()->toDateString(),
                    'priority' => $payload['priority'] ?? 'medium',
                    'status' => 'todo',
                ]);
                $executionResult = ['task_id' => $task->id, 'created' => true];
                break;

            case 'assign_lead':
                if (!empty($action->target_entity_id) && !empty($payload['assignee_id'])) {
                    $lead = Lead::where('tenant_id', $tenantId)->find($action->target_entity_id);
                    if ($lead) {
                        $lead->update(['assigned_to' => $payload['assignee_id']]);
                        $executionResult = ['lead_id' => $lead->id, 'assigned_to' => $payload['assignee_id']];
                    }
                }
                break;

            case 'update_lead':
                if (!empty($action->target_entity_id) && !empty($payload['fields'])) {
                    $lead = Lead::where('tenant_id', $tenantId)->find($action->target_entity_id);
                    if ($lead) {
                        // Whitelist permitted fields
                        $allowedFields = ['status', 'lead_score', 'notes', 'city'];
                        $safeFields = array_intersect_key($payload['fields'], array_flip($allowedFields));
                        $lead->update($safeFields);
                        $executionResult = ['lead_id' => $lead->id, 'updated_fields' => array_keys($safeFields)];
                    }
                }
                break;

            default:
                $executionResult = ['status' => 'acknowledged', 'message' => "Executed {$action->action_type} safely."];
                break;
        }

        $action->update([
            'status' => 'executed',
            'confirmed_by_user_id' => $user->id,
            'confirmed_at' => now(),
            'execution_result' => $executionResult,
        ]);

        return $action;
    }

    /**
     * Reject a proposed action
     */
    public function rejectAction(int $tenantId, int $actionId, User $user, ?string $reason = null): AiProposedAction
    {
        $action = AiProposedAction::where('tenant_id', $tenantId)->findOrFail($actionId);
        $action->update([
            'status' => 'rejected',
            'confirmed_by_user_id' => $user->id,
            'rejection_reason' => $reason ?: 'Rejected by user',
        ]);
        return $action;
    }
}
